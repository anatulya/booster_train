"""This script replays an InterMimic motion tensor and outputs it to a npz file.

The InterMimic file is a bare ``torch.float32`` tensor of shape ``(T, raw)`` sampled at a
fixed fps, with the layout built by ``_make_obs_layout(num_bodies, num_dof)``::

    root_pos      [0:3]                       world frame, m
    root_rot      [3:7]                       quaternion, xyzw
    root_lin_vel  [7:10]                      world frame, m/s
    root_ang_vel  [10:13]                     world frame, rad/s
    dof_pos       [13 : 13+ND]                rad
    dof_vel       [13+ND : 13+2*ND]           rad/s
    obj_pos       [13+2*ND : 16+2*ND]         world frame, m
    obj_rot       [16+2*ND : 20+2*ND]         quaternion, xyzw
    obj_lin_vel   [20+2*ND : 23+2*ND]         world frame, m/s
    obj_ang_vel   [23+2*ND : 26+2*ND]         world frame, rad/s
    body_*        [26+2*ND : 26+2*ND+13*NB]   ignored, regenerated from the Booster model
    contact       trailing NB                 per-body 0/1; CONTACT_CHANNELS carried through, and
                                              STANCE_CHANNELS as ``stance`` when the file has them

The object block is carried straight through to the output npz (as ``object_pos_w``,
``object_quat_w``, ``object_lin_vel_w``, ``object_ang_vel_w``): unlike the robot body block,
there is no differing source/target body set to reconcile, so no re-simulation is needed.

Reference points match Isaac Lab throughout: positions and orientations are link frame,
linear velocities are center of mass, and angular velocity is frame-independent. That is
exactly how ``write_root_state_to_sim`` reads a root state, so the root block transfers
with no conversion beyond the quaternion layout.

Unlike :file:`csv_to_npz.py`, joint and root velocities are taken straight from the file
rather than finite-differenced from the positions, so fast parts of the motion keep their
true derivatives. The body blocks are still discarded and regenerated by driving the
Booster articulation, because the source model exposes a different body set, ordering and
link geometry than the Booster K1 model the policy is trained against.

.. code-block:: bash

    # Bake only
    python pt_to_npz.py --headless \
        --input_file ./booster_assets/motions/K1/sub4_smallbox_047_smallbox_intermimic_original.pt \
        --output_name ./booster_assets/motions/K1/sub4_smallbox_047.npz

    # Bake + offline/headless MP4 render
    python pt_to_npz.py --headless \
        --input_file ./booster_assets/motions/K1/sub4_smallbox_047_smallbox_intermimic_original.pt \
        --output_name ./booster_assets/motions/K1/sub4_smallbox_047.npz \
        --video ./sub4_smallbox_047.mp4
"""

